export const SITE_COPY_BUNDLES = Object.freeze({ en: EN, zh: ZH, es: ES, ...EXTRA_SITE_COPY_BUNDLES });

export function createSiteCopy(language = "") {
  const normalized = normalizeSiteLanguage(language);
  const locale = Object.hasOwn(SITE_COPY_BUNDLES, normalized.uiCode) ? normalized.uiCode : "en";
  const messages = SITE_COPY_BUNDLES[locale];
  return {
    language: normalized,
    locale,
    t(key, params = {}) {
      const template = messages[key] ?? EN[key] ?? key;
      return Object.entries(params).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value ?? "")),
        template
      );
    },
  };
}
