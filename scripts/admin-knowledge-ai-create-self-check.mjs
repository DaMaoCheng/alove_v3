import assert from "node:assert/strict";
import { closeDbPool, getDbPool, initializeDatabase } from "../server/db.js";
import { createKnowledgeBaseFromAi } from "../server/admin-knowledge-service.js";

const knowledgeBaseId = `kb_self_check_${Date.now()}`;

await initializeDatabase();
try {
  const result = await createKnowledgeBaseFromAi({
    id: knowledgeBaseId,
    label: "Self-check Knowledge",
    category: "football",
    priority: 80,
    keywords: "世界杯, 赛制",
    fuzzyKeywords: "晋级, 小组赛",
    sourceText: "2026 世界杯扩军到 48 支球队。小组赛和淘汰赛规则需要拆成不同知识片段，方便看板娘和网红角色按问题召回。",
  }, {
    ai: async (draft) => ({
      summary: `${draft.label} summary generated by AI`,
      sections: [
        {
          title: "世界杯赛制",
          summary: "说明 2026 世界杯扩军和晋级规则。",
          content: "2026 世界杯将有 48 支球队参赛，知识库需要记录小组赛、淘汰赛和晋级路径。",
          exactKeywords: ["2026世界杯", "48队"],
          fuzzyKeywords: ["晋级规则", "小组赛"],
          order: 10,
        },
        {
          title: "客服使用方式",
          summary: "说明客服如何引用这一段知识。",
          content: "当用户询问世界杯赛制时，AI 应优先引用准确规则，再用简短自然语言解释。",
          exactKeywords: ["客服话术"],
          fuzzyKeywords: ["解释规则"],
          order: 20,
        },
      ],
    }),
  });

  assert.equal(result.ok, true, "create result should be ok");
  assert.equal(result.item.id, knowledgeBaseId, "returned knowledge base id should match");
  assert.equal(result.item.summary, "Self-check Knowledge summary generated by AI", "AI summary should be saved on knowledge_bases");
  assert.equal(result.item.category, "football", "category should be saved");
  assert.equal(result.item.priority, 80, "priority should be saved");
  assert.deepEqual(result.item.keywords, ["世界杯", "赛制"], "exact keywords should be saved");
  assert.deepEqual(result.item.fuzzyKeywords, ["晋级", "小组赛"], "fuzzy keywords should be saved");
  assert.equal(result.item.sections.length, 2, "AI sections should be saved as knowledge_sections rows");
  assert.equal(result.item.sections[0].title, "世界杯赛制", "section title should come from AI outline split");
  assert.equal(result.item.sections[0].summary, "说明 2026 世界杯扩军和晋级规则。", "section summary should be saved");
  assert.match(result.item.sections[0].content, /48 支球队/, "section content should be saved");
  assert.deepEqual(result.item.sections[0].keywords, ["2026世界杯", "48队"], "section exact keywords should be saved");
  assert.deepEqual(result.item.sections[0].fuzzyKeywords, ["晋级规则", "小组赛"], "section fuzzy keywords should be saved");

  const [[baseRow]] = await getDbPool().execute("SELECT id, summary FROM knowledge_bases WHERE id = ? LIMIT 1", [knowledgeBaseId]);
  assert.equal(baseRow.summary, "Self-check Knowledge summary generated by AI", "knowledge_bases row should contain AI summary");

  const [sectionRows] = await getDbPool().execute(
    "SELECT title, summary, content, keywords_json, fuzzy_keywords_json FROM knowledge_sections WHERE knowledge_base_id = ? ORDER BY display_order ASC",
    [knowledgeBaseId]
  );
  assert.equal(sectionRows.length, 2, "knowledge_sections should contain one row per AI section");
  assert.equal(sectionRows[1].title, "客服使用方式", "second section should be persisted");

  console.log("admin knowledge AI create self-check passed");
} finally {
  await getDbPool().execute("DELETE FROM knowledge_bases WHERE id = ?", [knowledgeBaseId]).catch(() => {});
  await closeDbPool();
}
