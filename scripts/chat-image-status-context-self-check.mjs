import assert from 'node:assert/strict';
process.env.AIOVE_PROVIDER_LOG_WRITE_ENABLED = 'false';
globalThis.fetch = async () => { throw new Error('Network forbidden in isolated check'); };
const { resolveChatImageStatusContext, refreshChatImageStatusContext, toImageStatusReviewContext, getChatImageStatusFallbackCopy, buildCurrentImageDeliveryContract, buildImageRepresentationContract } = await import('../server/chat-image-status-context-service.js');
const { buildChatImageContextLayer } = await import('../server/chat-prompt-layers.js');
const { getChatImageHistoricalReadyCopy, getChatImageStatusCopy } = await import('../server/chat-image-copy-service.js');
const currentDelivery = { kind: "library", status: "ready", currentTurn: true };
const deliveryContract = buildCurrentImageDeliveryContract(currentDelivery);
assert(deliveryContract.includes("chat image message"), "a source asset delivered this turn is a real new chat message");
assert(buildImageRepresentationContract(currentDelivery).includes("not a user-interface location"), "library source cannot become a gallery UI claim");
for (const fact of [null, { ...currentDelivery, currentTurn: false }, { ...currentDelivery, status: "unknown" }, { ...currentDelivery, status: "queued" }, { ...currentDelivery, currentRequest: { outcome: "not_created" } }]) {
  assert.equal(buildCurrentImageDeliveryContract(fact), "", "only verified current ready permits this delivery contract");
}
const pendingFact = { kind: "generated", status: "queued", currentTurn: true };
assert(buildImageRepresentationContract(pendingFact).includes("confirms that request is pending"));
assert.equal(buildImageRepresentationContract({ kind: "unknown", status: "unknown" }), "");
assert(buildImageRepresentationContract({ ...pendingFact, currentTurn: false }).includes("earlier image task"));
assert(!buildImageRepresentationContract({ ...pendingFact, currentTurn: false }).includes("created the current"));
assert(!buildImageRepresentationContract(currentDelivery).includes("confirms that request is pending"));
const { buildReplyReviewMessages } = await import('../server/chat-reply-review-contracts.js');
const reviewMessages = buildReplyReviewMessages({ boundaryReviewRequired: true, imageStatusContext: currentDelivery });
assert(reviewMessages.some(m => m.content.includes(deliveryContract)), "review must use the same authoritative delivery contract as generation");
assert(buildChatImageContextLayer({ imageStatus: currentDelivery }).content.includes(deliveryContract));
assert(reviewMessages.some(m => m.content.includes("merchandise browsing")), "the photo branch must scope browsing prohibition to commerce");
assert(!reviewMessages.some(m => m.content.includes("reject any product, browsing, discount or purchase invitation")), "do not leave an opposing blanket browsing rule in the photo branch");
const pendingReview = buildReplyReviewMessages({ boundaryReviewRequired: true, imageStatusContext: pendingFact });
assert(pendingReview.some(m => m.content.includes(buildImageRepresentationContract(pendingFact))));
assert(buildChatImageContextLayer({ imageStatus: pendingFact }).content.includes(buildImageRepresentationContract(pendingFact)));
const session = { id: 'session-a', internal_uid: 'user-a', character_id: 'character-a' };
const row = { id: 'image-a', content_type: 'image_generation', display_order: 91, asset_id: 'asset-a', image_status: 'generating' };
const calls = [];
const db = { execute: async (sql, args) => { calls.push({sql,args}); return [[row]]; } };
const context = await resolveChatImageStatusContext(db, { session, character: {id:'character-a'}, userDisplayOrder: 100 });
assert.equal(context.imageStatus.status, 'generating');
assert.equal(context.imageStatus.currentTurn, false);
assert.equal(calls.length, 1);
assert.match(calls[0].sql, /s.internal_uid <=> \?/);
assert.match(calls[0].sql, /s.guest_session_id <=> \?/);
assert.match(calls[0].sql, /m.character_id = \?/);
assert.match(calls[0].sql, /LIMIT 20/);
assert.match(calls[0].sql, /next_user.display_order/);
assert.deepEqual(calls[0].args.slice(0,4), ['session-a','user-a',null,'character-a']);
const freshCalls=[];
const freshDb={execute:async(sql,args)=>{freshCalls.push({sql,args});return [[{...row,image_status:'ready'}]];}};
const ready=await refreshChatImageStatusContext(freshDb,context);
assert.equal(ready.imageStatus.status,'ready');
assert.match(freshCalls[0].sql,/m.id = \?/);
assert.ok(freshCalls[0].args.includes('image-a'));
assert.equal(toImageStatusReviewContext(ready).status,'ready');
assert.equal(JSON.stringify(toImageStatusReviewContext(ready)).includes('asset-a'),false);
assert.match(buildChatImageContextLayer(ready).content,/ready/);
assert.doesNotMatch(buildChatImageContextLayer(ready).content,/as if the shot is being taken/);
assert.equal(getChatImageStatusFallbackCopy(ready,'fr'),getChatImageHistoricalReadyCopy('fr'));
assert.notEqual(getChatImageStatusFallbackCopy(ready,'fr'),'Photo prête.','historical ready cannot announce a new photo');
const missing=await refreshChatImageStatusContext({execute:async()=>[[]]},ready);
assert.equal(missing.imageStatus.status,'unknown');
const broken=await refreshChatImageStatusContext({execute:async()=>{throw Error('offline');}},ready);
assert.equal(broken.imageStatus.status,'unknown');
const gallery=await resolveChatImageStatusContext({execute:async()=>[[{id:'gallery-a',content_type:'mascot_library_image',display_order:101}]]},{session,character:{id:'character-a'},userDisplayOrder:100,directive:{taskCreated:true}});
assert.equal(gallery.imageStatus.kind,'library');
assert.equal(gallery.imageStatus.status,'ready');
assert.equal(getChatImageStatusFallbackCopy(gallery,'fr'),getChatImageStatusCopy({language:'fr',status:'ready'}),'a confirmed current-turn delivery retains the original ready acknowledgement');
assert.match(buildChatImageContextLayer(gallery).content,/pre-existing media asset/);
assert.doesNotMatch(buildChatImageContextLayer(gallery).content,/already created an image task/);
assert.equal(await resolveChatImageStatusContext({execute:async()=>[[]]},{session,character:{id:'character-a'},userDisplayOrder:100}),null);
assert.equal(await resolveChatImageStatusContext(db,{session:{...session,internal_uid:null},character:{id:'character-a'},userDisplayOrder:100}),null);
assert.equal(await resolveChatImageStatusContext(db,{session,character:{id:'other'},userDisplayOrder:100}),null);
const failed=await refreshChatImageStatusContext({execute:async()=>[[{...row,image_status:'failed'}]]},context);
assert.equal(failed.imageStatus.status,'failed');
assert.doesNotMatch(getChatImageStatusFallbackCopy(failed,'en'),/preparing|ready/i);
const { SUPPORTED_CHARACTER_LANGUAGES } = await import('../shared/language-library.js');
for (const {code} of SUPPORTED_CHARACTER_LANGUAGES) {
  assert.ok(getChatImageStatusFallbackCopy(failed,code));
  assert.ok(getChatImageStatusFallbackCopy(missing,code));
  assert.notEqual(getChatImageStatusFallbackCopy(failed,code), getChatImageStatusFallbackCopy(context,code));
  assert.equal(getChatImageStatusFallbackCopy(ready,code),getChatImageHistoricalReadyCopy(code));
  assert.notEqual(getChatImageStatusFallbackCopy(ready,code),getChatImageStatusCopy({language:code,status:'ready'}),'history must be qualified in every supported character language');
  if (code !== 'en') assert.notEqual(getChatImageStatusFallbackCopy(missing,code),getChatImageStatusFallbackCopy(missing,'en'));
}
