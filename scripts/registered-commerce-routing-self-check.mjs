import assert from "node:assert/strict";
process.env.AIOVE_PROVIDER_LOG_WRITE_ENABLED = "false";
globalThis.fetch = async () => { throw new Error("Unexpected external request in isolated registered routing check"); };
const { buildChatProductRecommendationContext } = await import("../server/chat-product-recommendation-service.js");
const { buildProductContextLayer } = await import("../server/chat-prompt-layers.js");
const { selectProductsForMessage } = await import("../server/chat-product-reply-service.js");
const character = { id: "mascot_test", category_id: "mascot", site_id: "test" };
const site = { id: "test", slug: "test", currency: "HUF", product_api_url: "https://catalog.invalid/api/products" };
const db = { execute: async () => [[site]] };
const products = Array.from({ length: 5 }, (_, i) => ({ id: `p${i}`, name: `Arsenal Home Shirt ${i}`, price: "3000 HUF", stock: "In stock", url: `https://shop.invalid/p${i}` }));
let sourceCalls = 0;
const fetchProducts = async (_url, intent) => { sourceCalls += 1; assert.match(intent.query, /arsenal/i); return products; };
const singleProductRequest = { relation: "single", action: "new", items: [], selectedIndex: null, selectionEvidence: "" };
const decide = (route, needsLiveProductData = false, confident = true) => async () => ({ route, needsLiveProductData, confident, confidence: confident ? .95 : .2, topic: "price", searchQuery: "Arsenal shirt",
  ...(confident ? { productRequest: { ...singleProductRequest, relation: ["product_search", "product_question"].includes(route) ? "single" : "none" } } : {}) });
let metadata;
const question = await buildChatProductRecommendationContext(db, { character, userText: "Mennyibe kerül az Arsenal mez?", fetchProducts, classifyCommerce: decide("product_question", true), onCommerceDecision: (value) => { metadata = value; } });
assert.equal(metadata.commerceRoute, "product_question");
assert.equal(question.cardAllowed, false);
assert.equal(question.products.length, 5);
assert.deepEqual(selectProductsForMessage(question), []);
const layer = buildProductContextLayer(character, question, "Mennyibe kerül?");
assert.match(layer.content, /3000 HUF/);
assert.match(layer.content, /No new product card/);
assert.doesNotMatch(layer.content, /exactly one short emotional follow-up/);
for (const route of ["product_question", "store_policy", "chat"]) {
  const calls = sourceCalls;
  const result = await buildChatProductRecommendationContext(db, { character, userText: "Arsenal shirt", fetchProducts, classifyCommerce: decide(route), onCommerceDecision: (value) => { metadata = value; } });
  assert.equal(result, null);
  assert.equal(sourceCalls, calls);
  assert.equal(metadata.commerceRoute, route);
}
const shopping = await buildChatProductRecommendationContext(db, { character, userText: "Arsenal shirt", fetchProducts, classifyCommerce: decide("product_search", true) });
assert.equal(shopping.cardAllowed, true);
assert.equal(selectProductsForMessage(shopping).length, 1);
const callsBeforeUncertain = sourceCalls;
const uncertain = await buildChatProductRecommendationContext(db, { character, userText: "Arsenal shirt", fetchProducts, classifyCommerce: decide("chat", false, false) });
assert.equal(uncertain.products.length, 0);
assert.equal(sourceCalls, callsBeforeUncertain);
assert.equal(uncertain.cardAllowed, false);
assert.equal(uncertain.searchIntent.shouldLoadProductContext, false);
assert.equal(uncertain.searchIntent.commerceRoute, "unclear");
let warnings = [];
const warn = console.warn;
console.warn = (...args) => warnings.push(JSON.stringify(args));
let failed;
try {
  failed = await buildChatProductRecommendationContext(db, { character, userText: "Arsenal shirt", classifyCommerce: decide("product_question", true), fetchProducts: async () => { const error = new Error("secret-token-raw-response"); error.statusCode = 429; throw error; } });
} finally { console.warn = warn; }
assert.equal(failed.searchIntent.sourceErrorCode, "rate_limited");
assert.equal(failed.cardAllowed, false);
assert.ok(warnings.length);
assert.ok(!warnings.join(" ").includes("secret-token-raw-response"));
const callsBeforeLegacy = sourceCalls;
const legacy = await buildChatProductRecommendationContext(db, { character, userText: "Arsenal shirt", classifyIntent: async () => { throw new Error("must not call old classifier"); }, fetchProducts });
assert.equal(legacy.products.length, 0);
assert.equal(legacy.cardAllowed, false);
assert.equal(legacy.searchIntent.shouldLoadProductContext, false);
assert.equal(sourceCalls, callsBeforeLegacy);
let businessDbCalls = 0;
const forbiddenDb = { execute: async () => { businessDbCalls += 1; throw new Error("business chat must not access DB"); } };
assert.equal(await buildChatProductRecommendationContext(forbiddenDb, { character, userText: "I want to collaborate with Nike on my business project", classifyCommerce: decide("chat") }), null);
assert.equal(await buildChatProductRecommendationContext(forbiddenDb, { character, userText: "I want to collaborate with Nike on my business project", classifyIntent: async () => ({ isProductRequest: true }) }), null);
assert.equal(businessDbCalls, 0);
let collaborationClassifications = 0;
const designer = await buildChatProductRecommendationContext(db, { character, userText: "Which designer does Nike collaborate with on this jersey?", classifyCommerce: async () => { collaborationClassifications += 1; return { route: "product_question", confident: true, confidence: .95, needsLiveProductData: false, topic: "material", productRequest: singleProductRequest }; }, onCommerceDecision: (value) => { metadata = value; }, fetchProducts });
assert.equal(designer, null);
assert.equal(collaborationClassifications, 1);
assert.equal(metadata.commerceRoute, "product_question");
assert.equal(metadata.nonShoppingReason, "");
const recentCard = { senderType: "character", product: { ...products[2], siteId: "test", siteSlug: "test" } };
const anchoredOptions = { character, userText: "What does that one cost?", recentMessages: [recentCard], classifyCommerce: async () => ({ route: "product_question", topic: "price", confident: true, confidence: .98, needsLiveProductData: true, searchQuery: "Arsenal shirt", referencedProductId: "p2", productRequest: singleProductRequest }) };
const anchored = await buildChatProductRecommendationContext(db, { ...anchoredOptions, fetchProducts });
assert.equal(anchored.searchIntent.query, products[2].name);
assert.equal(anchored.searchIntent.referencedProductId, "p2");
assert.deepEqual(anchored.products.map((product) => product.id), ["p2"]);
assert.deepEqual(selectProductsForMessage(anchored), []);
const missingReference = await buildChatProductRecommendationContext(db, { ...anchoredOptions, fetchProducts: async () => products.filter((product) => product.id !== "p2") });
assert.equal(missingReference.products.length, 0);
assert.equal(missingReference.sourceRef, "site-product-no-match");
for (const foreignProduct of [{ ...recentCard.product, siteId: "other", siteSlug: "other" }, { ...recentCard.product, siteId: "", siteSlug: "" }]) {
  const calls = sourceCalls;
  const crossSite = await buildChatProductRecommendationContext(db, { ...anchoredOptions, recentMessages: [{ senderType: "character", product: foreignProduct }], fetchProducts, onCommerceDecision: (value) => { metadata = value; } });
  assert.equal(crossSite, null);
  assert.equal(sourceCalls, calls);
  assert.equal(metadata.unresolvedProductReference, true);
}
const callsBeforeHallucination = sourceCalls;
const hallucinated = await buildChatProductRecommendationContext(db, { ...anchoredOptions, classifyCommerce: async () => ({ route: "product_question", topic: "price", confident: true, confidence: .98, needsLiveProductData: true, searchQuery: "Arsenal shirt", referencedProductId: "invented", productRequest: singleProductRequest }), fetchProducts, onCommerceDecision: (value) => { metadata = value; } });
assert.equal(hallucinated, null);
assert.equal(sourceCalls, callsBeforeHallucination);
assert.equal(metadata.unresolvedProductReference, true);
console.log("registered commerce routing self-check passed (isolated DB/source/classifier; no external calls)");
