import assert from 'node:assert/strict';
import { buildReplyReviewMessages } from '../server/chat-reply-review-contracts.js';
import { applyCommerceQuestionPromptPolicy } from '../server/commerce-routing-service.js';
const prompt=applyCommerceQuestionPromptPolicy({systemPrompt:'base',layers:[]},{commerceRoute:'store_policy',answerRequired:true,knowledgeScope:'business'}).systemPrompt;
assert.match(prompt,/Do not infer any qualifying products/);
assert.match(prompt,/current verified campaign evidence/);
const review=buildReplyReviewMessages({businessFactsRequired:true,text:'test',speechText:'test',userText:'test'}).filter(x=>x.role==='system').map(x=>x.content).join('\n');
assert.match(review,/common practice do not verify/);
assert.match(review,/both campaign and relevant cart evidence/);
assert.match(review,/Accept honest uncertainty/);
assert.match(review,/pure general definition/);
assert.match(review,/even a conditional or generalized list/);
assert.match(review,/verified campaign evidence for a campaign rule/);
const chat=buildReplyReviewMessages({businessFactsRequired:false,text:'test',speechText:'test',userText:'test'}).filter(x=>x.role==='system').map(x=>x.content).join('\n');
assert.doesNotMatch(chat,/common practice do not verify/);
console.log('Promotion evidence policy scoped to business review; fixture-only, no model/DB');
assert.match(prompt,/Do not quote, echo, play along with/);
assert.match(prompt,/Respect any refusal of contact/);
assert.match(review,/reject either output that repeats/);
assert.match(review,/verified contact can be used only if contact is allowed/);
assert.match(review,/not normal casual chat/);
assert.doesNotMatch(chat,/user abuse as untrusted context/);
console.log('Complaint tone and support boundaries scoped to business review; fixture-only, no model/DB');
assert.match(prompt,/Do not be defensive or sarcastic/);
assert.match(review,/helped more than the customer previously received/);
assert.doesNotMatch(chat,/helped more than the customer previously received/);
