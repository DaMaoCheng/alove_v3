export function buildGuestProductTonePrefix(tone = "direct", languageCode = "en") {
  const language = resolveGuestProductReplyLanguage(languageCode);
  const index = ["warm", "playful", "encouraging"].indexOf(tone);
  return index < 0 ? "" : TONE_PREFIXES[language][index];
}

export const GUEST_PRODUCT_REPLY_COPY = Object.freeze(Object.fromEntries(
  Object.entries(COPY_ROWS).map(([code, row]) => [code, Object.freeze(Object.fromEntries(FIELDS.map((field, index) => [field, row[index]])))]),
));

export function resolveGuestProductReplyLanguage(languageCode = "", userText = "") {
  const normalized = normalizeCharacterLanguage(languageCode)
    || normalizeCharacterLanguage(String(languageCode || "").trim().toLowerCase().split(/[-_]/)[0]);
  if (normalized && GUEST_PRODUCT_REPLY_COPY[normalized.code]) return normalized.code;
  return /[\u3400-\u9fff]/.test(String(userText || "")) ? "zh" : "en";
}

export function buildGuestProductReplyCopy(key, { languageCode = "", userText = "", values = {} } = {}) {
  const language = resolveGuestProductReplyLanguage(languageCode, userText);
  const template = GUEST_PRODUCT_REPLY_COPY[language][key];
  if (!template) throw new Error(`Unknown guest product reply key: ${key}`);
  return template.replace(/\{(team|variant|phrase)\}/g, (_, field) => String(values[field] || "").trim());
}

export function buildGuestProductSourceErrorReply({ sourceErrorCode = "", languageCode = "", userText = "" } = {}) {
  const keys = {
    [PRODUCT_SOURCE_ERROR_CODE.MARKET_CURRENCY_MISMATCH]: "configuration",
    [PRODUCT_SOURCE_ERROR_CODE.MARKET_COUNTRY_AMBIGUOUS]: "configuration",
    [PRODUCT_SOURCE_ERROR_CODE.SOURCE_UNCONFIGURED]: "configuration",
    [PRODUCT_SOURCE_ERROR_CODE.CREDENTIALS_UNAVAILABLE]: "credentials",
    [PRODUCT_SOURCE_ERROR_CODE.AUTH_FAILED]: "credentials",
    [PRODUCT_SOURCE_ERROR_CODE.TIMEOUT]: "timeout",
    [PRODUCT_SOURCE_ERROR_CODE.RATE_LIMITED]: "rateLimit",
  };
  const key = Object.hasOwn(keys, sourceErrorCode) ? keys[sourceErrorCode] : "unavailable";
  return buildGuestProductReplyCopy(key, { languageCode, userText });
}

export function buildUnconfirmedProductStateReply({ searchIntent = {}, searchOutcome = "", sourceErrorCode = "", languageCode = "", userText = "" } = {}) {
  if (hasPendingProductRequest(searchIntent)) return searchIntent.replyBoundary?.salesAllowed === false
    ? buildGuestProductReplyCopy("clarification", { languageCode, userText })
    : buildProductRequestScopeCopy(searchIntent, { languageCode: languageCode || resolveGuestProductReplyLanguage(languageCode, userText) });
  const outcome = resolveUnconfirmedProductSearchOutcome(searchIntent, searchOutcome);
  const label = productScopeResultLabel(searchIntent, { languageCode: languageCode || resolveGuestProductReplyLanguage(languageCode, userText) });
  if (outcome === "source_error") {
    const result = buildGuestProductSourceErrorReply({
      sourceErrorCode: searchIntent.replyBoundary?.contactAllowed === false ? "" : (sourceErrorCode || searchIntent.sourceErrorCode),
      languageCode, userText,
    });
    return label ? `${label}\n\n${result}` : result;
  }
  const key = searchIntent.replyBoundary?.salesAllowed === false ? "clarification"
    : outcome === "no_match" ? "noMatch"
      : outcome === "clarification_exhausted" ? "exhausted" : "clarification";
  const result = buildGuestProductReplyCopy(key, { languageCode, userText });
  return label ? `${label}\n\n${result}` : result;
}
