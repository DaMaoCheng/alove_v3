const SIZING_SOURCE = Symbol('exact-current-product-sizing-source');

function sizingSnapshot(product) {
  const safe = toGuestSafeProduct(product);
  return { productId: safe.productId, name: safe.name, siteId: String(product.siteId || product.site_id || ''), siteSlug: String(product.siteSlug || product.site_slug || ''),
    sizeChartResolved: product.sizeChartResolved === true, sizeChart: safe.sizeChart,
    sizes: safe.sizes.map(({label, available}) => ({label, available})) };
}

function verifiedSizingSnapshot(product, site) {
  const proof = product?.[SIZING_SOURCE];
  if (!proof || proof.siteId !== site?.id || proof.siteSlug !== site?.slug || product.sizeChartResolved !== true) return null;
  const snapshot = sizingSnapshot(product);
  return snapshot.productId && snapshot.name && snapshot.siteId === site.id && snapshot.siteSlug === site.slug
    && JSON.stringify(snapshot) === proof.snapshot ? snapshot : null;
}

// Only a factory-proven exact read can supply current sizing facts. A flag,
// a serialized card or a same-shaped client object is never source authority.
export function toTrustedProductSizingReviewContext(options = {}) {
  const context = options.productContext, intent = options.searchIntent || context?.searchIntent || {};
  const character = options.catalogueOwner?.character || options.character || {};
  const site = options.catalogueOwner?.trustedSite || options.trustedSite;
  if (options.sizingRequired !== true || !site?.id || !site.slug || !character.id
    || !isCurrentCatalogueOwner({character, trustedSite:site, siteId:site.id})
    || context?.sourceType !== 'product_api' || !['current-product-sizing-context','guest-current-product-sizing-context'].includes(context.sourceRef)
    || context.siteId !== site.id || context.siteSlug !== site.slug || context.searchOutcome !== 'matched'
    || context.sourceErrorCode || context.snapshotOnly || context.candidateContext || context.products?.length
    || intent.sourceErrorCode || intent.scopeUnverified || intent.productScopePending || intent.unresolvedProductReference
    || intent.commerceClassificationUnavailable || intent.commerceClassificationFailure || intent.nonShoppingReason
    || intent.childSizingUpdateOnly || intent.referencedSiteId && intent.referencedSiteId !== site.id
    || intent.referencedSiteSlug && intent.referencedSiteSlug !== site.slug) return null;
  const snapshot = verifiedSizingSnapshot(context.sizingProduct, site);
  if (!snapshot || intent.referencedProductId && intent.referencedProductId !== snapshot.productId
    || JSON.stringify(snapshot).length > 20000) return null;
  return { ...snapshot, productCardDelivery:{count:0},
    limitation:'Only this exact current item size labels, availability and source chart are supplied. Missing units stay unknown; raw source values are not corrected or converted. No fit guarantee, identity confirmation, new card or store policy is established.' };
}

// Numeric cell values are source quotations, not language generated by the
// character. Keep this bounded exception private-proof-led and exact-only.
export function trustedSizingLiteralSourceSpans({text='', speechText='', retainedText='', ...options} = {}) {
  const source = toTrustedProductSizingReviewContext(options);
  if (!source?.sizeChart) return [];
  const outputs = [text, speechText || text, retainedText].filter(value => typeof value === 'string');
  const spans = [], seen = new Set();
  let length = 0;
  for (const row of source.sizeChart.rows) for (const value of row) {
    if (seen.has(value) || !/^(?=.*\d)[\d\s.,/+–—~()%\-]{1,80}$/u.test(value)
      || !outputs.some(output => output.includes(value)) || spans.length >= 16 || length + value.length > 400) continue;
    spans.push(value); seen.add(value); length += value.length;
  }
  return spans;
}

// The final router already authorized this owned catalogue target. Supplying a
// size may refine a literal name just as it refines a team; it is not a reason
// to replace that search with the no-current-card sizing guidance path.
export function hasOwnedSizingProductSearch({ site = {}, characterId = '', searchIntent = {} } = {}) {
  if (searchIntent.commerceRoute !== 'product_search' || searchIntent.searchState !== 'ready_to_search'
    || searchIntent.primarySearchVerified !== true || searchIntent.primarySearchBlocked
    || searchIntent.shouldLoadProductContext !== true || searchIntent.cardAllowed !== true
    || searchIntent.replyBoundary?.salesAllowed !== true || searchIntent.candidateSearchAllowed !== true
    || searchIntent.sourceErrorCode || searchIntent.nonShoppingReason || searchIntent.scopeUnverified
    || searchIntent.productScopePending || searchIntent.unresolvedProductReference
    || hasPendingProductRequest(searchIntent) || searchIntent.candidateConfirmationOnly) return false;
  const location = { siteId: site.id, characterId };
  const read = value => readProductCandidateState([{ senderType: 'character', productCandidateState: value }], location);
  const target = read(searchIntent.productCandidateState);
  if (target?.status !== 'active' || target.owner !== 'single' || target.proposal || target.suspectedTerm) return false;
  return JSON.stringify(target.requirements) === JSON.stringify(read({ ...target, requirements: searchIntent })?.requirements);
}

export function selectCurrentProductForSizing({ site = {}, searchIntent = {}, recentMessages = [] } = {}) {
  if (searchIntent.unresolvedProductReference === true
    || (searchIntent.referencedSiteId && String(searchIntent.referencedSiteId) !== String(site.id))
    || (searchIntent.referencedSiteSlug && String(searchIntent.referencedSiteSlug) !== String(site.slug))) return null;
  if (!searchIntent.referencedProductId) return findRecentProductMessage(recentMessages)?.product || null;
  return recentMessages.slice(-12).reverse().map((message) => message.product).find((product) => product?.name
    && String(product.productId || product.id || "") === String(searchIntent.referencedProductId)
    && String(product.siteId || product.site_id || "") === String(site.id)
    && String(product.siteSlug || product.site_slug || "") === String(site.slug)) || null;
}

export function sanitizeProductSizingChart(chart) {
  return toGuestSafeProduct({ sizeChart: chart }).sizeChart;
}

export async function resolveTrustedCurrentProductSizing({ site = {}, product = {}, resolveProduct = resolveProductCheckoutProduct } = {}) {
  const fallback = { ...product, sizeChart: null, sizeChartResolved: false };
  if (!site?.id || !site.slug || String(product.siteId || product.site_id || "") !== String(site.id)
    || String(product.siteSlug || product.site_slug || "") !== String(site.slug)) return fallback;
  if (!isSameResolvedProductIdentity(product, product)) return fallback;
  if (verifiedSizingSnapshot(product, site)) return product;
  if (!product.productId && !product.id && !product.url) return fallback;
  try {
    const result = await resolveProduct({ siteSlug: site.slug, product, strictSite: true, exactProduct: true });
    const source = result?.sourceItem;
    if (result?.resolvedFromSource !== true || String(result.site?.id || "") !== String(site.id)
      || String(result.site?.slug || "") !== String(site.slug) || !source || !isSameResolvedProductIdentity(product, source)
      || source.siteId && String(source.siteId) !== site.id || source.site_id && String(source.site_id) !== site.id
      || source.siteSlug && source.siteSlug !== site.slug || source.site_slug && source.site_slug !== site.slug) return fallback;
    // URL-only identity additionally requires a configured or server-verified
    // storefront origin; the merged/client item never grants provenance.
    if (!(product.productId || product.id) || !(source.productId || source.id)) {
      const origin = new URL(product.url).origin;
      const allowed = new Set(getServerProductOrigins(result));
      for (const url of [site.site_url, site.siteUrl, site.storefrontUrl, result.site.siteUrl, result.site.storefrontUrl]) {
        try { allowed.add(new URL(url).origin); } catch { /* absent site origin */ }
      }
      if (!allowed.has(origin)) return fallback;
    }
    const chart = sanitizeProductSizingChart(source.sizeChart);
    if (source.sizeChartResolved !== true || (source.sizeChart && !chart)) return fallback;
    const resolved = { ...product, sizes: Array.isArray(source.sizes) ? source.sizes : [], sizeChart: chart, sizeChartResolved: true };
    const snapshot = sizingSnapshot(resolved);
    if (!snapshot.name || !isSameResolvedProductIdentity(resolved, resolved)) return fallback;
    // Preserve the existing verified URL-only rendering path, but it cannot
    // acquire the new exact-ID audit/literal authority.
    if (!(product.productId || product.id) || !(source.productId || source.id)) return resolved;
    if (snapshot.productId !== String(product.productId || product.id)) return fallback;
    resolved[SIZING_SOURCE] = Object.freeze({siteId:site.id, siteSlug:site.slug, snapshot:JSON.stringify(snapshot)});
    return resolved;
  } catch { return fallback; }
}

export function formatTrustedProductSizingFacts(product = {}) {
  const safe = toGuestSafeProduct({ ...product, sizes: Array.isArray(product.sizes) ? product.sizes.map((size) => typeof size === "string" ? { label: size } : size) : [] });
  const labels = safe.sizes.map((size) => `${size.label} [${size.available === true ? "available" : size.available === false ? "not available" : "availability unverified"}]`).join(", ");
  const facts = [safe.name ? `Verified product: ${safe.name}.` : "", labels ? `Listed size labels: ${labels}.` : "No verified size labels supplied."];
  if (product.sizeChartResolved !== true || (product.sizeChart && !safe.sizeChart)) return [...facts, "Size chart is not verified; lookup was not completed or failed. Do not infer that this product has no chart."].filter(Boolean).join("\n");
  if (!safe.sizeChart) return [...facts, "The source lookup completed without returning a verified size chart. Do not infer measurements or guarantee fit."].filter(Boolean).join("\n");
  const chart = safe.sizeChart;
  return [...facts, `Verified size chart: ${chart.title}.`, chart.unit ? `Explicit chart units: ${chart.unit}.` : "Chart units were not supplied. Do not assume units.", chart.columns.join(" | "), ...chart.rows.map((row) => row.join(" | ")), "Use only these product-specific measurements and stated units; do not guarantee fit."].filter(Boolean).join("\n");
}
